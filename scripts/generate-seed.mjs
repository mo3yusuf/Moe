#!/usr/bin/env node
// Generates supabase/seed.sql from scripts/demo-data.mjs.
// Usage: node scripts/generate-seed.mjs
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEMO_PASSWORD, restaurants, sampleClips, users, videos } from './demo-data.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Deterministic UUID (v4 layout) from a namespace + key, so tests can reference demo rows. */
export function demoId(ns, key) {
  const h = createHash('sha256').update(`crave-demo:${ns}:${key}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs) => `array[${xs.map(q).join(', ')}]::text[]`;
const out = [];
const emit = (s) => out.push(s);

emit(`-- =============================================================================
-- CRAVE DEMO SEED — GENERATED by scripts/generate-seed.mjs. Do not edit by hand.
-- Fictional restaurants/people for DEVELOPMENT ONLY. Never load into production.
-- Demo login password for every account: ${DEMO_PASSWORD}
-- =============================================================================
set session_replication_role = default;
`);

// Markets
emit(`insert into public.markets (code, city, region, country_code, timezone, currency, tax_name, tax_rate_bps, prices_include_tax, center_lat, center_lng, service_radius_km, is_active) values
  ('au-bne', 'Brisbane', 'QLD', 'AU', 'Australia/Brisbane', 'AUD', 'GST', 1000, true, -27.4698, 153.0251, 25, true),
  ('au-syd', 'Sydney', 'NSW', 'AU', 'Australia/Sydney', 'AUD', 'GST', 1000, true, -33.8688, 151.2093, 25, false),
  ('au-mel', 'Melbourne', 'VIC', 'AU', 'Australia/Melbourne', 'AUD', 'GST', 1000, true, -37.8136, 144.9631, 25, false)
on conflict (code) do nothing;
`);

emit(`insert into public.platform_settings (key, value, description) values
  ('default_commission', '{"bps": 1000}', 'Default restaurant commission (basis points). 1000 = 10%.'),
  ('customer_fees', '{"serviceFeeCents": 0, "serviceFeeBps": 0, "serviceFeeCapCents": null, "smallOrderThresholdCents": 0, "smallOrderFeeCents": 0}', 'Customer-facing fees. All zero at launch.'),
  ('delivery', '{"enabled": false}', 'Delivery module is disabled until a delivery provider is integrated.'),
  ('creator_affiliate', '{"enabled": false, "defaultRateBps": 0}', 'Creator affiliate rewards (later phase).')
on conflict (key) do nothing;

insert into public.delivery_providers (code, name, is_enabled) values
  ('uber_direct', 'Uber Direct (not integrated)', false),
  ('doordash_drive', 'DoorDash Drive (not integrated)', false)
on conflict (code) do nothing;
`);

// Users
const uid = (key) => demoId('user', key);
for (const u of users) {
  emit(`insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, confirmation_token, recovery_token, email_change_token_new, email_change, raw_app_meta_data, raw_user_meta_data, created_at, updated_at)
values ('00000000-0000-0000-0000-000000000000', ${q(uid(u.key))}, 'authenticated', 'authenticated', ${q(u.email)}, extensions.crypt(${q(DEMO_PASSWORD)}, extensions.gen_salt('bf')), now(), '', '', '', '', '{"provider":"email","providers":["email"]}', ${q(JSON.stringify({ display_name: u.name }))}, now(), now())
on conflict (id) do nothing;
insert into auth.identities (provider_id, user_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (${q(uid(u.key))}, ${q(uid(u.key))}, ${q(JSON.stringify({ sub: uid(u.key), email: u.email, email_verified: true }))}, 'email', now(), now(), now())
on conflict do nothing;
update public.profiles set username = ${q(u.username)}, display_name = ${q(u.name)}, date_of_birth_confirmed_16_plus = true where id = ${q(uid(u.key))};`);
  for (const r of u.roles) emit(`insert into public.user_roles (user_id, role) values (${q(uid(u.key))}, '${r}') on conflict do nothing;`);
  if (u.creator) emit(`insert into public.creator_profiles (user_id, is_verified) values (${q(uid(u.key))}, true) on conflict do nothing;`);
}
emit(`insert into public.privacy_consents (user_id, consent, granted, policy_version, source)
select id, c, true, 'demo-2026-11', 'app' from auth.users, unnest(array['terms_of_service', 'privacy_policy', 'personalisation']::public.consent_type[]) c
where email like '%@demo.crave.local';
update public.user_preferences set favourite_cuisines = array['Japanese', 'Lebanese'], onboarding_completed_at = now() where user_id = ${q(uid('customer'))};
`);

// Restaurants
const rid = (key) => demoId('restaurant', key);
const lid = (key) => demoId('location', key);
const iid = (r, i) => demoId('item', `${r}:${i}`);
for (const r of restaurants) {
  emit(`
-- ${r.name}
insert into public.restaurants (id, slug, name, description, market_id, status, cuisines, price_level, accepting_orders, pickup_enabled, accepts_advance_orders, avg_prep_minutes, verified_dietary, rating_avg, rating_count, is_demo, created_by, verified_at)
values (${q(rid(r.key))}, ${q(r.slug)}, ${q(r.name)}, ${q(r.description)}, (select id from public.markets where code = 'au-bne'), '${r.status}', ${arr(r.cuisines)}, ${r.priceLevel}, ${r.status === 'active'}, true, ${!!r.advanceOrders}, ${r.prep}, ${arr(r.verifiedDietary)}, ${(4.2 + (r.key.length % 7) / 10).toFixed(1)}, ${40 + r.key.length * 13}, true, ${q(uid(r.owner))}, ${r.status === 'active' ? 'now()' : 'null'})
on conflict (id) do nothing;
insert into public.restaurant_verifications (restaurant_id, legal_business_name, abn, gst_registered, business_contact_name, business_contact_email, business_contact_phone, food_business_licence_number, licensing_council, status, submitted_by, reviewed_at)
values (${q(rid(r.key))}, ${q(r.name.replace(' (DEMO)', ' Pty Ltd (DEMO)'))}, '51824753556', true, ${q(users.find((u) => u.key === r.owner).name)}, ${q(users.find((u) => u.key === r.owner).email)}, '0700000000', 'DEMO-FBL-${r.key.toUpperCase()}', 'Brisbane City Council', '${r.status === 'active' ? 'approved' : 'submitted'}', ${q(uid(r.owner))}, ${r.status === 'active' ? 'now()' : 'null'});
insert into public.restaurant_locations (id, restaurant_id, street_line, suburb, state, postcode, lat, lng, timezone, pickup_instructions)
values (${q(lid(r.key))}, ${q(rid(r.key))}, ${q(r.location.street)}, ${q(r.location.suburb)}, 'QLD', ${q(r.location.postcode)}, ${r.location.lat}, ${r.location.lng}, 'Australia/Brisbane', 'DEMO — collect from the front counter, show your order number.')
on conflict (id) do nothing;`);
  for (const h of r.hours) emit(`insert into public.opening_hours (location_id, day_of_week, opens_at, closes_at) values (${q(lid(r.key))}, ${h.day}, '${h.opens}', '${h.closes}');`);

  const menuId = demoId('menu', r.key);
  emit(`insert into public.menus (id, restaurant_id, name) values (${q(menuId)}, ${q(rid(r.key))}, 'Main menu') on conflict do nothing;`);
  const categories = [...new Set(r.items.map((i) => i.category))];
  categories.forEach((c, idx) =>
    emit(`insert into public.menu_categories (id, menu_id, restaurant_id, name, sort_order) values (${q(demoId('category', `${r.key}:${c}`))}, ${q(menuId)}, ${q(rid(r.key))}, ${q(c.replace(/\b\w/g, (m) => m.toUpperCase()))}, ${idx}) on conflict do nothing;`),
  );
  r.items.forEach((item, idx) => {
    emit(`insert into public.menu_items (id, restaurant_id, category_id, name, description, price_cents, cuisine, food_category, tags, dietary_attributes, allergens, spice_level, sort_order)
values (${q(iid(r.key, item.key))}, ${q(rid(r.key))}, ${q(demoId('category', `${r.key}:${item.category}`))}, ${q(item.name)}, ${q(item.description)}, ${item.price}, ${q(item.cuisine)}, ${q(item.category)}, ${arr(item.tags)}, ${arr(item.dietary)}, ${arr(item.allergens)}, ${item.spice}, ${idx})
on conflict (id) do nothing;`);
    item.groups.forEach((g, gi) => {
      const gid = demoId('group', `${r.key}:${item.key}:${g.name}`);
      emit(`insert into public.modifier_groups (id, menu_item_id, restaurant_id, name, min_select, max_select, sort_order) values (${q(gid)}, ${q(iid(r.key, item.key))}, ${q(rid(r.key))}, ${q(g.name)}, ${g.min}, ${g.max}, ${gi}) on conflict do nothing;`);
      g.options.forEach((o, oi) =>
        emit(`insert into public.modifier_options (id, group_id, restaurant_id, name, price_delta_cents, is_default, sort_order) values (${q(demoId('option', `${r.key}:${item.key}:${g.name}:${o.name}`))}, ${q(gid)}, ${q(rid(r.key))}, ${q(o.name)}, ${o.delta}, ${!!o.isDefault}, ${oi}) on conflict do nothing;`),
      );
    });
  });
}

emit(`
-- Example negotiated commission agreement (8%) to demonstrate per-restaurant rates.
insert into public.commission_agreements (restaurant_id, commission_bps, notes)
values (${q(rid('nonna'))}, 800, 'DEMO — launch partner rate for first 6 months');
`);

// Videos
videos.forEach((v, idx) => {
  const id = demoId('video', v.key);
  const restaurant = v.restaurant ? restaurants.find((r) => r.key === v.restaurant) : null;
  const tags = (v.caption.match(/#[\p{L}\p{N}_]+/gu) ?? []).map((t) => t.slice(1).toLowerCase());
  emit(`insert into public.videos (id, uploader_id, uploader_kind, restaurant_id, market_id, playback_url, duration_ms, width, height, mime_type, caption, hashtags, status, is_sponsored, sponsor_disclosure, rights_basis, is_demo, view_count, published_at)
values (${q(id)}, ${q(uid(v.uploader))}, '${v.kind ?? 'creator'}', ${v.kind === 'restaurant' ? q(rid(restaurant.key)) : 'null'}, (select id from public.markets where code = 'au-bne'), ${q(sampleClips[idx % sampleClips.length])}, 15000, 1280, 720, 'video/mp4', ${q(v.caption)}, ${arr(tags)}, 'published', ${v.sponsored}, ${q(v.disclosure ?? null)}, '${v.kind === 'restaurant' ? 'restaurant_owned' : 'own_content'}', true, ${1000 + idx * 731}, now() - interval '${idx * 9} hours')
on conflict (id) do nothing;`);
  if (v.item) {
    emit(`insert into public.video_menu_items (video_id, menu_item_id, restaurant_id, status, requested_by, reviewed_at)
values (${q(id)}, ${q(iid(restaurant.key, v.item))}, ${q(rid(restaurant.key))}, '${v.link}', ${q(uid(v.uploader))}, ${v.link === 'approved' ? 'now()' : 'null'}) on conflict do nothing;`);
  }
  emit(`insert into public.video_trending_scores (video_id, market_id, score) values (${q(id)}, (select id from public.markets where code = 'au-bne'), ${((idx * 37) % 100) / 100}) on conflict do nothing;`);
});

emit(`
-- A little social graph
insert into public.user_follows (follower_id, followee_id) values (${q(uid('customer'))}, ${q(uid('creator1'))}) on conflict do nothing;
insert into public.restaurant_follows (user_id, restaurant_id) values (${q(uid('customer'))}, ${q(rid('kaizen'))}) on conflict do nothing;
insert into public.creator_permissions (restaurant_id, creator_id, permission) values (${q(rid('ember'))}, ${q(uid('creator1'))}, 'auto_approve_tags') on conflict do nothing;
`);

writeFileSync(join(root, 'supabase', 'seed.sql'), out.join('\n') + '\n');

// IDs for tests/apps that need to reference demo rows.
const ids = {
  users: Object.fromEntries(users.map((u) => [u.key, uid(u.key)])),
  restaurants: Object.fromEntries(restaurants.map((r) => [r.key, rid(r.key)])),
  locations: Object.fromEntries(restaurants.map((r) => [r.key, lid(r.key)])),
  items: Object.fromEntries(restaurants.flatMap((r) => r.items.map((i) => [`${r.key}:${i.key}`, iid(r.key, i.key)]))),
  options: Object.fromEntries(
    restaurants.flatMap((r) => r.items.flatMap((i) => i.groups.flatMap((g) => g.options.map((o) => [`${r.key}:${i.key}:${g.name}:${o.name}`, demoId('option', `${r.key}:${i.key}:${g.name}:${o.name}`)])))),
  ),
  videos: Object.fromEntries(videos.map((v) => [v.key, demoId('video', v.key)])),
};
writeFileSync(join(root, 'supabase', 'demo-ids.json'), JSON.stringify(ids, null, 2) + '\n');
console.log(`Wrote supabase/seed.sql (${out.length} statements) and supabase/demo-ids.json`);
